def main():
    wb = load_workbook(BOOK)
    ws = wb["1_改写任务"]

    filled = 0
    missing = []
    for r in range(2, ws.max_row + 1):
        qid = ws.cell(row=r, column=1).value
        draft = DRAFTS.get(qid)
        if draft:
            ws.cell(row=r, column=6, value=draft)
            filled += 1
        else:
            missing.append(qid)

    wb.save(BOOK)
    print(f"已填入 {filled} 行")
    if missing:
        print(f"未匹配 {len(missing)} 行: {missing}")
    extra = set(DRAFTS) - {ws.cell(row=r, column=1).value for r in range(2, ws.max_row + 1)}
    if extra:
        print(f"[警告] 有 {len(extra)} 个 id 不在表里: {extra}")


if __name__ == "__main__":
    main()
